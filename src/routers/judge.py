@router.get("/judge/{event_id}/pairwise")
def pairwise_judging(
    event_id: str,
    request: Request,
    db: Session = Depends(get_db),
    user: User = Depends(require_role("judge", "organizer", "admin")),
):
    event = db.get(Event, event_id)
    if event is None:
        raise HTTPException(status_code=404, detail="event not found")

    projects = get_judge_assigned_projects(db, event_id, user)

    if len(projects) < 2:
        return templates.TemplateResponse(
            request=request,
            name="judge/pairwise.html",
            context=base_context(
                request=request,
                event=event,
                user=user,
                role="judge",
                error="Not enough projects to compare.",
            ),
        )

    pairwise_stats = sync_pairwise_scores(db, event_id, user.id)
    existing = (
        db.query(PairwiseComparison)
        .filter_by(event_id=event_id, judge_id=user.id)
        .all()
    )

    # Intelligent pair selection: prioritize pairs that haven't been compared yet,
    # and projects with the fewest total comparisons.
    comp_counts = Counter()
    compared_pairs = set()
    for c in existing:
        comp_counts[c.winner_project_id] += 1
        comp_counts[c.loser_project_id] += 1
        pair_key = (
            min(c.winner_project_id, c.loser_project_id),
            max(c.winner_project_id, c.loser_project_id),
        )
        compared_pairs.add(pair_key)

    p_ids = [p.id for p in projects]
    p_map = {p.id: p for p in projects}
    uncompared_pairs = []
    for i in range(len(p_ids)):
        for j in range(i + 1, len(p_ids)):
            pair_key = (min(p_ids[i], p_ids[j]), max(p_ids[i], p_ids[j]))
            if pair_key not in compared_pairs:
                total_comparisons = comp_counts[p_ids[i]] + comp_counts[p_ids[j]]
                uncompared_pairs.append(
                    (total_comparisons, p_map[p_ids[i]], p_map[p_ids[j]])
                )

    if uncompared_pairs:
        uncompared_pairs.sort(key=lambda x: x[0])
        min_load = uncompared_pairs[0][0]
        candidates = [pair for pair in uncompared_pairs if pair[0] == min_load]
        _, p1, p2 = random.choice(candidates)
        if random.random() > 0.5:
            p1, p2 = p2, p1
    else:
        # All pairs compared at least once: pick the pair with the fewest comparisons
        all_pairs = []
        for i in range(len(p_ids)):
            for j in range(i + 1, len(p_ids)):
                pair_comps = sum(
                    1
                    for c in existing
                    if (
                        c.winner_project_id == p_ids[i]
                        and c.loser_project_id == p_ids[j]
                    )
                    or (
                        c.winner_project_id == p_ids[j]
                        and c.loser_project_id == p_ids[i]
                    )
                )
                all_pairs.append((pair_comps, p_map[p_ids[i]], p_map[p_ids[j]]))
        all_pairs.sort(key=lambda x: x[0])
        min_comps = all_pairs[0][0]
        candidates = [pair for pair in all_pairs if pair[0] == min_comps]
        _, p1, p2 = random.choice(candidates)
        if random.random() > 0.5:
            p1, p2 = p2, p1

    p1_stats = pairwise_stats.get(
        p1.id, {"elo": 1500.0, "wins": 0, "losses": 0, "score": 7}
    )
    p2_stats = pairwise_stats.get(
        p2.id, {"elo": 1500.0, "wins": 0, "losses": 0, "score": 7}
    )

    # Progress metrics for pairwise mode
    assigned_project_ids = {p.id for p in projects}
    assigned_count = len(assigned_project_ids)
    scores = db.query(Score).filter_by(event_id=event_id, judge_id=user.id).all()
    scored_project_ids = set(s.project_id for s in scores)
    reviewed_project_ids = scored_project_ids.intersection(assigned_project_ids)
    reviewed_count = len(reviewed_project_ids)
    remaining_count = max(0, assigned_count - reviewed_count)
    completion_pct = (
        min(100, round((reviewed_count / assigned_count) * 100))
        if assigned_count > 0
        else (100 if reviewed_count > 0 or not projects else 0)
    )
    metrics = {
        "assigned": assigned_count,
        "reviewed": reviewed_count,
        "remaining": remaining_count,
        "completion_pct": completion_pct,
    }

    return templates.TemplateResponse(
        request=request,
        name="judge/pairwise.html",
        context=base_context(
            request=request,
            event=event,
            user=user,
            role="judge",
            p1=p1,
            p2=p2,
            p1_stats=p1_stats,
            p2_stats=p2_stats,
            total_comparisons=len(existing),
            metrics=metrics,
        ),
    )


@router.post("/judge/{event_id}/pairwise")
async def submit_pairwise(
    event_id: str,
    request: Request,
    winner_id: str = Form(...),
    loser_id: str = Form(...),
    db: Session = Depends(get_db),
    user: User = Depends(require_role("judge", "organizer", "admin")),
):
    if winner_id != loser_id:
        p1 = db.get(Project, winner_id)
        p2 = db.get(Project, loser_id)
        if not p1 or not p2:
            raise HTTPException(status_code=400, detail="Invalid project ID")
        if p1.event_id != event_id or p2.event_id != event_id:
            raise HTTPException(
                status_code=400, detail="Projects must belong to this event"
            )
        if p1.is_draft or p1.is_disqualified or p2.is_draft or p2.is_disqualified:
            raise HTTPException(
                status_code=400, detail="Cannot compare draft or disqualified projects"
            )

        p1_title = p1.title if p1 else winner_id
        p2_title = p2.title if p2 else loser_id

        from sqlalchemy import or_, and_

        existing_comp = (
            db.query(PairwiseComparison)
            .filter(
                PairwiseComparison.event_id == event_id,
                PairwiseComparison.judge_id == user.id,
                or_(
                    and_(
                        PairwiseComparison.winner_project_id == winner_id,
                        PairwiseComparison.loser_project_id == loser_id,
                    ),
                    and_(
                        PairwiseComparison.winner_project_id == loser_id,
                        PairwiseComparison.loser_project_id == winner_id,
                    ),
                ),
            )
            .first()
        )
        if existing_comp:
            existing_comp.winner_project_id = winner_id
            existing_comp.loser_project_id = loser_id
            existing_comp.created_at = utcnow()
        else:
            db.add(
                PairwiseComparison(
                    event_id=event_id,
                    judge_id=user.id,
                    winner_project_id=winner_id,
                    loser_project_id=loser_id,
                    created_at=utcnow(),
                )
            )

        log_msg = f"Judge {user.name} preferred '{p1_title}' over '{p2_title}' in pairwise comparison"
        recent_log = (
            db.query(AuditLog)
            .filter(
                AuditLog.event_id == event_id,
                AuditLog.actor_id == user.id,
                AuditLog.message == log_msg,
            )
            .order_by(AuditLog.id.desc())
            .first()
        )
        if not recent_log:
            db.add(
                AuditLog(
                    event_id=event_id,
                    actor_id=user.id,
                    message=log_msg,
                    created_at=utcnow(),
                )
            )
        db.commit()
        # Immediately sync updated pairwise ELO to Score records
        sync_pairwise_scores(db, event_id, user.id)

    return RedirectResponse(f"/judge/{event_id}/pairwise", status_code=303)


@router.post("/judge/{event_id}/pairwise/reset")
async def reset_pairwise(
    event_id: str,
    request: Request,
    db: Session = Depends(get_db),
    user: User = Depends(require_role("judge", "organizer", "admin")),
):
    event = db.get(Event, event_id)
    if event is None:
        raise HTTPException(status_code=404, detail="event not found")

    # 1. Delete all pairwise comparisons made by this judge for this event
    db.query(PairwiseComparison).filter_by(
        event_id=event_id, judge_id=user.id
    ).delete(synchronize_session=False)

    # 2. Clean up any auto-generated pairwise Score records for this judge
    pairwise_scores = (
        db.query(Score)
        .filter_by(event_id=event_id, judge_id=user.id)
        .all()
    )
    for s in pairwise_scores:
        if s.comment and s.comment.startswith("Pairwise ELO:"):
            db.delete(s)

    # 3. Audit log
    db.add(
        AuditLog(
            event_id=event_id,
            actor_id=user.id,
            message=f"Judge {user.name} reset all pairwise comparisons",
            created_at=utcnow(),
        )
    )
    db.commit()

    import urllib.parse

    query = urllib.parse.urlencode(
        {
            "msg": "All pairwise comparisons and pairwise scores have been reset.",
            "msg_type": "info",
        }
    )
    return RedirectResponse(f"/judge/{event_id}/pairwise?{query}", status_code=303)
